CREATE EXTENSION IF NOT EXISTS postgis;
CREATE SCHEMA orbit_dev;
CREATE TABLE orbit_dev.lines (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    geom geometry(LineString, 2056) NOT NULL
);
CREATE TABLE orbit_dev.polygons (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    geom geometry(Polygon, 2056) NOT NULL
);
CREATE INDEX ON orbit_dev.lines USING gist (geom);
CREATE INDEX ON orbit_dev.polygons USING gist (geom);
