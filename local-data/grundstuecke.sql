CREATE TABLE IF NOT EXISTS orbit_dev.grundstuecke (
    fid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    t_id integer,
    bemerkung varchar(500),
    geom geometry(LineString, 2056) NOT NULL
);
CREATE INDEX IF NOT EXISTS grundstuecke_geom_idx ON orbit_dev.grundstuecke USING gist (geom);
CREATE TABLE IF NOT EXISTS orbit_dev.grundstuecke_import (
    singleton boolean PRIMARY KEY DEFAULT true CHECK (singleton),
    fingerprint text NOT NULL
);
